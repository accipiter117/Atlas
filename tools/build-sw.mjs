#!/usr/bin/env node
// Writes sw.js, the service worker (docs/PLAN.md sections 10 and 11; phase 21).
//
// Why: so the game installs on a phone (Add to Home Screen) and still opens and
// plays in flight mode. GitHub Pages has no build step, so "per build" means:
// this tool stamps sw.js with a hash of every file the game is made of (the
// page, styles, code, rules, text, the manifest). Any change gives a new hash,
// so the browser sees a new service worker, fills a fresh cache and drops the
// old one. npm run check runs it before every commit; CI fails if sw.js is
// out of date.
//
// What the worker does:
//   - on install, caches every app file (so even parts not yet opened, like
//     the Killzone platoon battle, work offline);
//   - code, rules and text: network first (you always get the newest when
//     online), falling back to the cache offline;
//   - art (assets/): cache first, kept across builds, since it rarely changes;
//   - a page load offline falls back to the cached index.html.
//
// Run:  node tools/build-sw.mjs [--verify] [root]

import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { listFiles } from './lib-files.mjs';

export async function appFiles(root) {
  const dirs = ['css', 'src', 'rules', 'text'];
  const files = ['index.html', 'manifest.webmanifest'];
  for (const d of dirs) files.push(...(await listFiles(root, join(root, d))));
  return files.filter((f) => /\.(html|css|js|json|webmanifest)$/.test(f) && !f.includes('/vendor/README')).sort();
}

export async function buildServiceWorker(root) {
  const files = await appFiles(root);
  const hash = createHash('sha256');
  for (const f of files) { hash.update(f); hash.update(await readFile(join(root, f))); }
  const build = hash.digest('hex').slice(0, 12);
  const precache = ['./', ...files];
  return `// Atlas service worker. Generated by tools/build-sw.mjs: do not edit by hand.
// Build ${build}: a new build gets a new cache; art is cached once and kept.
const BUILD = '${build}';
const CODE = \`atlas-\${BUILD}\`;
const ART = 'atlas-art-v1';
const PRECACHE = ${JSON.stringify(precache, null, 0).replace(/","/g, '",\n  "').replace('[', '[\n  ').replace(/]$/, ',\n]')};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CODE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('atlas-') && k !== CODE && k !== ART).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

async function networkFirst(request) {
  const cache = await caches.open(CODE);
  try {
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  } catch {
    const hit = await cache.match(request, { ignoreSearch: true });
    if (hit) return hit;
    if (request.mode === 'navigate') return (await cache.match('index.html')) ?? (await cache.match('./'));
    throw new Error('offline and not cached');
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(ART);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(url.pathname.includes('/assets/') ? cacheFirst(request) : networkFirst(request));
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? join(dirname(fileURLToPath(import.meta.url)), '..');
  const out = await buildServiceWorker(root);
  const path = join(root, 'sw.js');
  let before = null;
  try { before = await readFile(path, 'utf8'); } catch { /* first time */ }
  if (process.argv.includes('--verify')) {
    if (before !== out) { console.error('build-sw: sw.js is out of date; run npm run check (or node tools/build-sw.mjs) and commit it'); process.exit(1); }
    console.log('build-sw: sw.js is up to date');
  } else {
    if (before !== out) await writeFile(path, out);
    console.log(`build-sw: ${before === out ? 'unchanged' : 'written'} (${out.match(/Build (\w+)/)[1]})`);
  }
}
