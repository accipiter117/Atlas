#!/usr/bin/env node
// Data check (docs/PLAN.md section 11.3).
//
// Loads every mod in rules/index.json on its own (with whatever it depends
// on) and every standard stack listed there, and fails on any error, so a
// broken mod never reaches the game. Warnings are printed but do not fail.
// Also regenerates CREDITS.md from every mod's credits line and every sprite
// sheet's credits, and fails if a sheet a skin names is missing or uncredited.
//
// Run:  node tools/check-data.mjs [--quiet]

import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { writeFile, readFile } from 'node:fs/promises';
import { loadRuleset } from '../src/data/loader.js';
import { formatMessage } from '../src/data/report.js';
import { ENGINE_VERSION } from '../src/sim/index.js';
import { readRules, readEngineText } from './lib-mods.mjs';

/** A mod plus everything it depends on, dependencies first. */
function withDependencies(id, available, seen = new Set()) {
  if (seen.has(id)) return [];
  seen.add(id);
  const m = JSON.parse(available[id].manifest);
  return [...(m.dependsOn ?? []).flatMap((d) => withDependencies(d, available, seen)), id];
}

export async function checkData(root) {
  const { index, available } = await readRules(root);
  const text = await readEngineText(root);
  const stacks = [
    ...index.mods.map((m) => withDependencies(m.id, available)),
    ...(index.stacks ?? []),
  ];
  const seen = new Set();
  const results = [];
  const artStacks = [];
  for (const stack of stacks) {
    const name = stack.join(' + ');
    if (seen.has(name)) continue;
    seen.add(name);
    const result = loadRuleset({ available, selection: stack, engineVersion: ENGINE_VERSION });
    if (result.ok && (stack.length === 1 || index.mods.find((m) => m.id === stack.at(-1)) && JSON.parse(available[stack.at(-1)].manifest).type !== 'tweak')) artStacks.push({ name, ruleset: result.ruleset });
    results.push({
      name,
      ok: result.ok,
      hash: result.hash,
      errors: result.report.messages.filter((m) => m.level === 'error').map((m) => formatMessage(text, m)),
      warnings: result.report.messages.filter((m) => m.level === 'warning').map((m) => formatMessage(text, m)),
    });
  }

  const credits = ['# Credits', '', 'Generated by `tools/check-data.mjs` from each mod\'s `credits` line. Do not edit by hand.', '',
    'Atlas engine code: original work under the MIT licence (see `LICENSE`).', ''];
  for (const m of index.mods) {
    const manifest = JSON.parse(available[m.id].manifest);
    credits.push(`- **${manifest.name}** (\`${m.id}\` ${manifest.version}): ${manifest.credits}`);
  }
  // Sprite sheets named by any mod's skin must exist and carry credits (section 10.6).
  const sheetProblems = [];
  const sheets = new Map();
  for (const m of index.mods) {
    const mod = available[m.id];
    for (const [file, textData] of Object.entries(mod.files)) {
      if (!file.startsWith('skin/')) continue;
      let art = {};
      try { art = JSON.parse(textData).values?.art ?? {}; } catch { continue; }
      for (const [id, entry] of Object.entries(art)) if (entry?.sheet) sheets.set(entry.sheet, { id, mod: m.id });
    }
  }
  if (sheets.size) credits.push('', '## Sprite sheets', '');
  for (const [path, { id, mod }] of sheets) {
    let desc;
    try { desc = JSON.parse(await readFile(join(root, path), 'utf8')); } catch { sheetProblems.push(`${mod}: art ${id} points to ${path}, which is missing or not JSON`); continue; }
    if (!desc.credits) sheetProblems.push(`${path} has no credits`);
    try { await readFile(join(root, desc.src)); } catch { sheetProblems.push(`${path} points to image ${desc.src}, which is missing`); }
    credits.push(`- **${id}** (\`${path}\`): ${desc.credits ?? 'MISSING CREDITS'}`);
  }
  // Bundled fonts (graphics overhaul G1), from assets/fonts/credits.json written by tools/copy-fonts.mjs.
  try {
    const fonts = JSON.parse(await readFile(join(root, 'assets', 'fonts', 'credits.json'), 'utf8'));
    credits.push('', '## Fonts', '');
    for (const f of fonts) credits.push(`- **${f.family}**: ${f.licence} (${f.source}), from ${f.via}; licence in \`${f.licenceFile}\``);
  } catch { /* no bundled fonts */ }
  credits.push('', '## Icons', '', '- **Atlas icons** (`assets/icons.svg`, `assets/icons.png`): original pixel art drawn in code by `tools/gen/icons.mjs`, MIT licence.');
  credits.push('');
  return { results, credits: credits.join('\n'), sheetProblems, artStatus: artStatus(artStacks) };
}

/**
 * docs/ART_STATUS.md (section 10.5): every art id each ruleset and conversion
 * asks for, and whether it has real art (a skin entry, its own or its class's)
 * or is drawn as a code placeholder for now.
 */
function artStatus(stacks) {
  const out = ['# Art status', '', 'Generated by `tools/check-data.mjs`. Do not edit by hand. Every id below is drawn by a',
    'code placeholder until a skin gives it real art, so the game is always playable.', ''];
  for (const { name, ruleset } of stacks) {
    const art = ruleset.skin?.art ?? {};
    const rows = [];
    for (const u of Object.values(ruleset.units ?? {})) rows.push([u.sprite ?? `unit.${u.id}`, `unit.class.${u.class}`]);
    for (const b of [...Object.values(ruleset.buildings ?? {}), ...Object.values(ruleset.wonders ?? {})]) rows.push([b.icon ?? `building.${b.id}`, null]);
    for (const l of Object.values(ruleset.leaders ?? {})) rows.push([l.portrait ?? `leader.${l.id}`, null]);
    for (const r of Object.values(ruleset.religions ?? {})) rows.push([r.icon ?? `religion.${r.id}`, null]);
    const status = (id, cls) => (art[id] ? 'real art' : cls && art[cls] ? `class art (${cls})` : 'placeholder');
    const unique = [...new Map(rows.map(([id, cls]) => [id, status(id, cls)])).entries()].sort((a, b) => a[0].localeCompare(b[0]));
    const real = unique.filter(([, s]) => s !== 'placeholder').length;
    out.push(`## ${name}`, '', `${unique.length} art ids: ${real} with art, ${unique.length - real} on placeholders.`, '', '| Art id | Status |', '| --- | --- |');
    for (const [id, s] of unique) out.push(`| \`${id}\` | ${s} |`);
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const quiet = process.argv.includes('--quiet');
  const { results, credits, sheetProblems, artStatus: art } = await checkData(root);
  await writeFile(join(root, 'CREDITS.md'), credits);
  await writeFile(join(root, 'docs', 'ART_STATUS.md'), art);
  let failed = 0;
  for (const r of results) {
    if (!r.ok) failed += 1;
    if (!quiet || !r.ok) {
      console.log(`${r.ok ? 'ok  ' : 'FAIL'} ${r.name}  (rules ${r.hash}, ${r.errors.length} errors, ${r.warnings.length} warnings)`);
      for (const e of r.errors) console.log(`       error: ${e}`);
      if (!quiet) for (const w of r.warnings) console.log(`       warning: ${w}`);
    }
  }
  for (const p of sheetProblems) console.log(`FAIL sprite sheet: ${p}`);
  if (sheetProblems.length) failed += 1;
  if (failed) {
    console.error(`check-data: ${failed} stack(s) failed to load`);
    process.exit(1);
  }
  console.log(`check-data: ok (${results.length} stacks)`);
}
