#!/usr/bin/env node
// Fonts for the graphics overhaul (G1): Cinzel for headings and Alegreya Sans
// for text, both free under the SIL Open Font Licence. Copies the Latin .woff2
// files from the @fontsource packages (dev dependencies) into assets/fonts/,
// with each family's licence, so they work offline and need no font service.
// Writes css/fonts.css (@font-face rules) and assets/fonts/credits.json (read
// by tools/check-data.mjs for CREDITS.md).
//
// Run after npm ci: node tools/copy-fonts.mjs

import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = [
  { pkg: 'cinzel', family: 'Cinzel', faces: [['400', 'normal'], ['600', 'normal'], ['700', 'normal']], source: 'https://github.com/NDISCOVER/Cinzel' },
  { pkg: 'alegreya-sans', family: 'Alegreya Sans', faces: [['400', 'normal'], ['400', 'italic'], ['500', 'normal'], ['700', 'normal']], source: 'https://github.com/huertatipografica/Alegreya-Sans' },
];

const out = join(ROOT, 'assets', 'fonts');
await mkdir(out, { recursive: true });
const css = ['/* Generated by tools/copy-fonts.mjs: the bundled fonts (SIL Open Font Licence 1.1). */'];
const credits = [];
for (const f of FAMILIES) {
  const base = join(ROOT, 'node_modules', '@fontsource', f.pkg);
  const version = JSON.parse(await readFile(join(base, 'package.json'), 'utf8')).version;
  for (const [weight, style] of f.faces) {
    const file = `${f.pkg}-latin-${weight}-${style}.woff2`;
    await copyFile(join(base, 'files', file), join(out, file));
    css.push(`@font-face { font-family: "${f.family}"; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url("../assets/fonts/${file}") format("woff2"); }`);
  }
  await copyFile(join(base, 'LICENSE'), join(out, `LICENSE-${f.pkg}.txt`));
  credits.push({ family: f.family, licence: 'SIL Open Font Licence 1.1', source: f.source, via: `@fontsource/${f.pkg} ${version}`, licenceFile: `assets/fonts/LICENSE-${f.pkg}.txt` });
}
await writeFile(join(ROOT, 'css', 'fonts.css'), `${css.join('\n')}\n`);
await writeFile(join(out, 'credits.json'), `${JSON.stringify(credits, null, 2)}\n`);
console.log(`fonts: ${FAMILIES.reduce((n, f) => n + f.faces.length, 0)} faces copied to assets/fonts/`);
